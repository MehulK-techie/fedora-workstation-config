// The workstation's accent colour follows your wallpaper: its dominant vivid
// hue tints Alt+Tab, the calendar, top-bar hover, the dock and workspace
// thumbnails, the welcome line and the timer ring, and GNOME's own accent
// (so Files and other apps match). It updates when the wallpaper changes.
//
// config/theme.conf, yours in ~/.config/mk-workstation/theme.conf:
//   ACCENT=auto | #rrggbb      SYSTEM_ACCENT=on | off      (`mk accent`)
import GdkPixbuf from 'gi://GdkPixbuf';
import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import St from 'gi://St';
import { dominantHue, hsvToRgb, rgbToHsv } from './colour.js';

const DEFAULT = [0, 200, 255];
const USER_CONF = GLib.build_filenamev([GLib.get_user_config_dir(), 'mk-workstation', 'theme.conf']);
const DEFAULT_CONF = GLib.build_filenamev([GLib.get_user_data_dir(), 'mk-workstation', 'config', 'theme.conf']);
const CSS = GLib.build_filenamev([GLib.get_user_cache_dir(), 'mk-workstation', 'accent.css']);
// GNOME's accent choices and their hues.
const GNOME_ACCENTS = [['red', 0], ['orange', 28], ['yellow', 48], ['green', 135], ['teal', 175],
    ['blue', 212], ['purple', 275], ['pink', 330]];

let current = DEFAULT;

/** The accent as [r, g, b] in 0-255. */
export function accentRGB() {
    return current;
}

/** The accent and a companion colour 45° along the colour wheel, in 0-1. */
export function accentPairUnit() {
    const [h, s, v] = rgbToHsv(...current.map(c => c / 255));
    return [current.map(c => c / 255), hsvToRgb(h + 45, s, v).map(c => c / 255)];
}

function readConf() {
    const conf = {ACCENT: 'auto', SYSTEM_ACCENT: 'on'};
    for (const path of [DEFAULT_CONF, USER_CONF]) {
        try {
            const [ok, bytes] = GLib.file_get_contents(path);
            if (ok) {
                for (const line of new TextDecoder().decode(bytes).split('\n')) {
                    const m = line.match(/^\s*([A-Z_]+)\s*=\s*(\S*)/);
                    if (m)
                        conf[m[1]] = m[2];
                }
            }
        } catch (e) {
            // missing file: defaults
        }
    }
    return conf;
}

function hex(rgbHex) {
    const n = parseInt(rgbHex.replace('#', ''), 16);
    return Number.isNaN(n) ? null : [n >> 16 & 255, n >> 8 & 255, n & 255];
}

function stylesheet([r, g, b]) {
    const [h, s] = rgbToHsv(r / 255, g / 255, b / 255);
    const deep = hsvToRgb(h, Math.max(s, 0.75), 0.78).join(',');
    const light = hsvToRgb(h, Math.min(s, 0.45), 1).join(',');
    const c = `${r},${g},${b}`;
    return `/* Generated by mk-indicator from the wallpaper accent; do not edit. */
.switcher-list { border-color: rgba(${c},0.30); }
.switcher-list .item-box:selected { background-color: rgba(${c},0.16); border-color: rgba(${light},0.95); box-shadow: 0 0 22px 0 rgba(${c},0.38); }
.switcher-list .item-box:highlighted { border-color: rgba(${light},0.70); }
.switcher-list .separator { background: rgba(${c},0.24); }
.switcher-arrow { border-color: rgba(${light},0.70); color: rgba(${light},0.70); }
.switcher-arrow:highlighted { border-color: rgb(${light}); color: rgb(${light}); }
.calendar .calendar-day:hover { background-color: rgba(${c},0.16); box-shadow: 0 0 10px 0 rgba(${c},0.22); }
.calendar .calendar-day:active, .calendar .calendar-day:selected { background-color: rgba(${c},0.28); }
.calendar .calendar-today, .calendar .calendar-today:selected { background-color: rgb(${deep}); box-shadow: 0 0 14px 1px rgba(${c},0.55); }
.calendar .calendar-today:hover { background-color: rgb(${c}); }
.calendar .calendar-day-with-events { color: rgb(${light}); }
.calendar .pager-button:hover, .calendar .calendar-month-label:hover { background-color: rgba(${c},0.18); }
.datemenu-today-button .day-label { color: rgb(${light}); }
.events-button:hover, .world-clocks-button:hover, .weather-button:hover { background-color: rgba(${c},0.12); box-shadow: inset 0 0 0 1px rgba(${c},0.30); }
#panel .panel-button:hover { box-shadow: inset 0 0 0 1px rgba(${c},0.35); }
#dashtodockContainer .overview-tile:hover .overview-icon, #dashtodockContainer .show-apps:hover .overview-icon { background-color: rgba(${c},0.08); box-shadow: 0 0 10px 0 rgba(${c},0.18); }
.workspace-thumbnail-indicator { border-color: rgba(${light},0.85); }
`;
}

export class Accent {
    enable(onChange) {
        this._onChange = onChange;
        this._cancel = new Gio.Cancellable();
        this._bg = new Gio.Settings({schema_id: 'org.gnome.desktop.background'});
        this._iface = new Gio.Settings({schema_id: 'org.gnome.desktop.interface'});
        this._ids = [
            [this._bg, this._bg.connect('changed::picture-uri', () => this.update())],
            [this._bg, this._bg.connect('changed::picture-uri-dark', () => this.update())],
            [this._iface, this._iface.connect('changed::color-scheme', () => this.update())],
        ];
        // GNOME replaced the shell theme (e.g. high contrast): load ours into
        // the new one. Loading a stylesheet also emits 'changed', so only act
        // when the theme itself is new.
        const context = St.ThemeContext.get_for_stage(global.stage);
        this._ids.push([context, context.connect('changed', () => {
            if (context.get_theme() !== this._theme)
                this._load();
        })]);
        GLib.mkdir_with_parents(GLib.path_get_dirname(USER_CONF), 0o755);
        this._monitor = Gio.File.new_for_path(USER_CONF).monitor_file(Gio.FileMonitorFlags.NONE, null);
        this._monitor.connect('changed', () => this.update());
        this.update();
    }

    update() {
        const conf = readConf();
        const fixed = conf.ACCENT !== 'auto' && hex(conf.ACCENT);
        if (fixed) {
            this._apply(fixed, conf);
            return;
        }
        const dark = this._iface.get_string('color-scheme') === 'prefer-dark';
        const uri = (dark && this._bg.get_string('picture-uri-dark')) || this._bg.get_string('picture-uri');
        let stream;
        try {
            stream = Gio.File.new_for_uri(uri).read(null);
        } catch (e) {
            this._apply(DEFAULT, conf);
            return;
        }
        // Decode a small copy off the main thread, so a 4K wallpaper can't
        // make the shell hitch.
        GdkPixbuf.Pixbuf.new_from_stream_at_scale_async(stream, 64, 64, true, this._cancel, (_s, res) => {
            let rgb = DEFAULT;
            try {
                const hue = dominantHue(GdkPixbuf.Pixbuf.new_from_stream_finish(res), 0.35);
                if (hue !== null)
                    rgb = hsvToRgb(hue, 0.72, 0.98);
            } catch (e) {
                // XML slideshows, unusual formats: keep the default
            }
            stream.close(null);
            this._apply(rgb, conf);
        });
    }

    _apply(rgb, conf) {
        current = rgb;
        try {
            GLib.mkdir_with_parents(GLib.path_get_dirname(CSS), 0o755);
            GLib.file_set_contents(CSS, stylesheet(rgb));
        } catch (e) {
            console.warn(`mk-indicator: accent stylesheet: ${e.message}`);
        }
        this._load();
        if (conf.SYSTEM_ACCENT !== 'off') {
            const [h, s] = rgbToHsv(...rgb.map(c => c / 255));
            const name = s < 0.2 ? 'slate'
                : GNOME_ACCENTS.reduce((best, [n, hue]) => {
                    const d = Math.min(Math.abs(h - hue), 360 - Math.abs(h - hue));
                    return d < best[1] ? [n, d] : best;
                }, ['blue', 999])[0];
            if (this._iface.get_string('accent-color') !== name)
                this._iface.set_string('accent-color', name);
        }
        this._onChange?.(rgb);
    }

    _load() {
        const theme = St.ThemeContext.get_for_stage(global.stage).get_theme();
        const file = Gio.File.new_for_path(CSS);
        if (this._loaded && this._theme === theme)
            theme.unload_stylesheet(this._loaded);
        this._theme = theme;
        this._loaded = null;
        if (file.query_exists(null)) {
            theme.load_stylesheet(file);
            this._loaded = file;
        }
    }

    disable() {
        this._cancel?.cancel();
        this._monitor?.cancel();
        this._ids?.forEach(([obj, id]) => obj.disconnect(id));
        this._ids = null;
        if (this._loaded && this._theme === St.ThemeContext.get_for_stage(global.stage).get_theme())
            this._theme.unload_stylesheet(this._loaded);
        this._loaded = this._theme = null;
        current = DEFAULT;
    }
}
